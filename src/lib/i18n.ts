const catalogs: Record<Locale, Record<MessageKey, string>> = { 'en-US': en, 'zh-CN': zh };

export function translate(locale: Locale, key: MessageKey | string, args: Record<string, string | number> = {}): string {
  const catalog = catalogs[locale] ?? catalogs['en-US'];
  const template = catalog[key as MessageKey] ?? catalogs['en-US'][key as MessageKey] ?? key;
  return template.replace(/\{(\w+)\}/g, (_, name: string) => String(args[name] ?? `{${name}}`));
}

export function number(locale: Locale, value?: number): string {
  return value === undefined ? translate(locale, 'usage.unavailable') : new Intl.NumberFormat(locale).format(value);
}

export function duration(locale: Locale, milliseconds?: number): string {
  if (milliseconds === undefined) return translate(locale, 'usage.unavailable');
  const seconds = Math.max(0, Math.round(milliseconds / 1000));
  const minutes = Math.floor(seconds / 60);
  const rest = seconds % 60;
  return minutes ? `${minutes}:${String(rest).padStart(2, '0')}` : `${rest}s`;
}

export function money(locale: Locale, value?: { amount: number; currency: string }): string {
  if (!value) return translate(locale, 'usage.unavailable');
  return new Intl.NumberFormat(locale, { style: 'currency', currency: value.currency }).format(value.amount);
}

